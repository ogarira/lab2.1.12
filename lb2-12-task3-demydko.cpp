#include <iostream> // підключення бібліотеки для роботою з потоками введення/виведення (cout, cin)
#include <Windows.h> // підключення системних функцій Windows для кодування консолі
#include <string> // підключення типом даних для текстових повідомлень
using namespace std; // використання стандартного простору імен std
int main() { // головна функція програми
SetConsoleCP(65001); // налаштування UTF-8 для зчитування з клавіатури
SetConsoleOutputCP(65001); // налаштування UTF-8 для виведення тексту українською
int mainLoop = 1; // змінна для керування повторним запуском усієї гри
do { // головний цикл повтору обслуговування нової компанії
system("cls"); // очищення екрана перед початком роботи
cout << "====================================================\n"; // привітання
cout << "   Ласкаво просимо до інтерактивного кафетерію!     \n";
cout << "====================================================\n\n";
int peopleCount; // оголошення змінної для кількості людей
cout << "Введіть кількість гостей у вашій компанії: "; // запит кількості гостей
cin >> peopleCount; // зчитування кількості людей у змінну peopleCount
double grandTotal = 0.0; // змінна для збереження сумарної вартості всього замовлення
int totalItemsCount = 0; // змінна для збереження загальної кількості замовлених позицій
for (int i = 1; i <= peopleCount; i++) { // цикл для почергового обслуговування кожного клієнта
system("cls"); // очищення консолі для оформлення замовлення поточного клієнта
cout << "----------------------------------------------------\n";
cout << "              ОБСЛУГОВУВАННЯ КЛІЄНТА № " << i << "\n"; // номер поточного клієнта
cout << "----------------------------------------------------\n";
double clientTotal = 0.0; // сума замовлення для поточного клієнта
int clientItemsCount = 0; // кількість вибраних позицій поточним клієнтом
int addMore = 1; // для циклу вибору страв

            do { // цикл, що дозволяє клієнту обирати декілька позицій з меню
                cout << "\n--- МЕНЮ КАФЕТЕРІЮ ---\n"; // виведення асортименту кави, чаїв, соків та тістечок
                cout << "1. Кава Еспресо      - 45.00 грн\n";
                cout << "2. Кава Капучино     - 60.00 грн\n";
                cout << "3. Чай Зелений       - 40.00 грн\n";
                cout << "4. Чай Чорний        - 40.00 грн\n";
                cout << "5. Сік Апельсиновий  - 50.00 грн\n";
                cout << "6. Тістечко Наполеон - 75.00 грн\n";
                cout << "7. Тістечко Чізкейк  - 85.00 грн\n";
                cout << "----------------------\n";
                int choice; // змінна для номеру обраної позиції
                cout << "Оберіть номер позиції (1-7): "; // запит вибору
                cin >> choice; // зчитування вибору клієнта
                switch (choice) { // розгалуження залежно від вибору пункту меню
                case 1:
                    clientTotal += 45.00; // додавання вартості Еспресо до чека клієнта
                    clientItemsCount++; // збільшення лічильника замовлених страв
                    cout << "-> Додано: Кава Еспресо (45.00 грн)\n";
                    break;
                case 2:
                    clientTotal += 60.00; // додавання вартості Капучино
                    clientItemsCount++;
                    cout << "-> Додано: Кава Капучино (60.00 грн)\n";
                    break;
                case 3:
                    clientTotal += 40.00; // додавання вартості Зеленого чаю
                    clientItemsCount++;
                    cout << "-> Додано: Чай Зелений (40.00 грн)\n";
                    break;
                case 4:
                    clientTotal += 40.00; // додавання вартості Чорного чаю
                    clientItemsCount++;
                    cout << "-> Додано: Чай Чорний (40.00 грн)\n";
                    break;
                case 5:
                    clientTotal += 50.00; // додавання вартості Соку
                    clientItemsCount++;
                    cout << "-> Додано: Сік Апельсиновий (50.00 грн)\n";
                    break;
                case 6:
                    clientTotal += 75.00; // додавання вартості Наполеона
                    clientItemsCount++;
                    cout << "-> Додано: Тістечко Наполеон (75.00 грн)\n";
                    break;
                case 7:
                    clientTotal += 85.00; // додавання вартості Чізкейка
                    clientItemsCount++;
                    cout << "-> Додано: Тістечко Чізкейк (85.00 грн)\n";
                    break;
                default:
                    cout << "[Помилка]: Некоректний вибір! Спробуйте ще раз.\n"; // обробка невірно введеного номера
                    break;
                }

                cout << "\nБажаєте додати ще щось для Клієнта №" << i << "? (1 - так, 0 - ні): "; // питаємо чи бажає клієнт ще страв
                cin >> addMore; // зчитуємо прапорець продовження для клієнта

            } while (addMore != 0); // повторюємо, якщо введено 1 (або будь-яке число, крім 0)

            grandTotal += clientTotal; // додаємо підсумок клієнта до загальної суми компанії
            totalItemsCount += clientItemsCount; // додаємо кількість позицій клієнта до загальної кількості

            cout << "\n>>> Замовлення Клієнта №" << i << " завершено. Сума: " << clientTotal << " грн (" << clientItemsCount << " позицій) <<<\n";
            system("pause"); // затримка перед переходом до наступного клієнта
        }

        system("cls"); // очищення екрана для виведення фінального чека
        cout << "====================================================\n";
        cout << "            ПІДСУМКОВИЙ ЧЕК ДЛЯ КОМПАНІЇ            \n"; // заголовок підсумкового чека
        cout << "====================================================\n";
        cout << " Обслуговано гостей:       " << peopleCount << " осіб\n"; // вивід кількості клієнтів
        cout << " Загальна кількість страв: " << totalItemsCount << " шт.\n"; // вивід загальної кількості страв
        cout << " Загальна сума до сплати:  " << grandTotal << " грн\n"; // вивід загальної суми замовлення
        cout << "====================================================\n\n";

        system("pause"); // затримка консолі

        cout << "\nЗапустити обслуговування нової компанії? (1 - так, 0 - ні): "; // запит на повтор гри
        cin >> mainLoop; // зчитування відповіді

    } while (mainLoop != 0); // якщо введено 0, гра завершується

    return 0; // повернення значення 0 при успішному завершенні програми
}
