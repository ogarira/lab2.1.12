#include <iostream> // підключення бібліотеки для стандартного введення/виведення (cin, cout)
#include <cmath> // підключення математичної бібліотеки для функцій fabs() та atan()
#include <Windows.h> // підключення системної бібліотеки Windows для налаштування кодування та команд консолі

using namespace std; // використання стандартного простору імен std

int main() { // головна функція програми, з якої починається її виконання
    SetConsoleCP(65001); // налаштування кодової сторінки UTF-8 для введення українських літер з клавіатури
    SetConsoleOutputCP(65001); // налаштування кодової сторінки UTF-8 для коректного виводу українських літер у консоль

    int continueProgram; // оголошення цілочислової змінної-прапорця для керування повторним запуском циклу

    do { // початок циклу з післяумовою do-while для забезпечення багаторазового виконання меню
        system("cls"); // системна команда для очищення консолі перед кожним новим відображенням меню

        int Pr; // оголошення змінної Pr для збереження обраного користувачем пункту меню (1, 2 або 3)
        cout << "Оберіть дію (параметр Pr):\n"; // виведення заголовка меню
        cout << "1 - Обчислити n-й елемент ряду\n"; // пункт 1: обчислення одного окремого елемента u_n
        cout << "2 - Обчислити суму перших n елементів ряду\n"; // пункт 2: обчислення суми фіксованої кількості n елементів
        cout << "3 - Обчислити суму ряду з точністю Eps = 10^-5\n"; // пункт 3: обчислення нескінченної суми із заданою точністю
        cout << "Ваш вибір (1, 2 або 3): "; // виведення запрошення до введення
        cin >> Pr; // зчитування введеного користувачем числа у змінну Pr

        switch (Pr) { // оператор багатоваріантного розгалуження для переходу до відповідного case за значенням Pr
        case 1: { // блок коду для першого пункту меню (Pr = 1)
            int n; // оголошення змінної n для збереження номера елемента
            cout << "Введіть номер елемента n (n >= 0): "; // виведення прохання ввести номер n
            cin >> n; // зчитування введеного номера n з клавіатури

            double un = 1.0; // оголошення змінної un дійсного типу та задання початкового значення нульового члена (u_0 = 1)
            for (int m = 0; m < n; m++) { // цикл від 0 до n-1 для послідовного перерахунку елементів від u_0 до u_n
                un = un * (-(2.0 * m + 1.0) / (2.0 * m + 3.0)); // рекурентна формула для обчислення наступного члена через попередній
            }

            cout << "Елемент u_" << n << " = " << un << endl; // виведення значення шуканого n-го елемента у консоль
            break; // оператор переривання для виходу з конструкції switch після виконання case 1
        }
        case 2: { // блок коду для другого пункту меню (Pr = 2)
            int n; // оголошення змінної n для кількості елементів
            cout << "Введіть кількість елементів n (n > 0): "; // виведення прохання ввести кількість n
            cin >> n; // зчитування кількості елементів n

            double sum = 0.0; // оголошення накопичувальної змінної sum та її обнулення
            double u = 1.0; // початкове значення першого доданка ряду (u_0 = 1)

            for (int m = 0; m < n; m++) { // цикл робить n ітерацій для додавання перших n членів ряду
                sum += u; // додавання поточного члена ряду u до загальної суми sum
                u = u * (-(2.0 * m + 1.0) / (2.0 * m + 3.0)); // рекурентне обчислення наступного елемента для наступного кроку
            }

            cout << "Сума перших " << n << " елементів ряду = " << sum << endl; // виведення знайденої суми
            break; // вихід з оператора switch після виконання case 2
        }
        case 3: { // блок коду для третього пункту меню (Pr = 3)
            double eps = 1e-5; // задання величини точності Eps = 10^-5 (0.00001)[cite: 7]
            double sum = 0.0; // накопичувальна змінна sum для збереження обчисленої суми
            double u = 1.0; // початкове значення першого члена ряду (u_0 = 1)
            int m = 0; // лічильник кількості просумованих членів ряду

            while (fabs(u) >= eps) { // цикл виконується доти, доки модуль поточного доданка більший або дорівнює точності eps[cite: 7]
                sum += u; // накопичення суми шляхом додавання поточного елемента u
                u = u * (-(2.0 * m + 1.0) / (2.0 * m + 3.0)); // рекурентний перерахунок елемента ряду за формулою варіанта 12
                m++; // збільшення лічильника врахованих членів ряду на 1
            }

            double control = atan(1.0); // обчислення контрольного теоретичного значення Pi / 4 за допомогою arctg(1)[cite: 7]

            cout << "Обчислена сума ряду = " << sum << endl; // виведення накопиченої суми ряду[cite: 7]
            cout << "Кількість врахованих членів ряду = " << m << endl; // виведення кількості використаних членів ряду[cite: 7]
            cout << "Контрольне значення (Pi / 4) = " << control << endl; // виведення контрольного значення[cite: 7]
            cout << "Абсолютна похибка = " << fabs(sum - control) << endl; // виведення модульного відхилення знайденої суми від контролю[cite: 7]
            break; // вихід з оператора switch після виконання case 3
        }
        default: { // блок, який виконується у випадку введення числа, відмінного від 1, 2 або 3
            cout << "Некоректний вибір! Введіть значення 1, 2 або 3." << endl; // виведення повідомлення про помилку
            break; // вихід з оператора switch
        }
        } // закриваюча дужка switch

        system("pause"); // системна затримка екрана до натискання будь-якої клавіші користувачем
        cout << "\nБажаєте продовжити? (1 - так, 0 - ні): "; // виведення питання про повторний запуск
        cin >> continueProgram; // зчитування вибору користувача (1 або 0)

    } while (continueProgram != 0); // умова продовження цикла: продовжувати, якщо введено будь-яке число, крім 0

    return 0; // повернення коду 0, що свідчить про успішне завершення програми
} // закриваюча дужка функції main