#include <iostream> // підключення бібліотеки для стандартного введення/виведення (cout, cin)
#include <Windows.h> // підключення системної бібліотеки Windows для налаштування кодування та команд консолі
#include <cmath> // підключення математичної бібліотеки для функцій pow() та tan()

using namespace std; // використання стандартного простору імен std

int main() { // головна функція програми, з якої починається її виконання
    SetConsoleCP(65001); // налаштування кодової сторінки UTF-8 для введення українських літер з клавіатури
    SetConsoleOutputCP(65001); // налаштування кодової сторінки UTF-8 для коректного виводу українських літер у консоль

    double x0 = 1.0; // початкове значення аргументу x за варіантом
    double xk = 2.2; // кінцеве значення аргументу x за варіантом
    double dx = 0.2; // крок зміни аргументу x за варіантом
    double b = 3.2;  // значення константи b за варіантом

    int continueProgram; // оголошення змінної-прапорця для керування повторним запуском програми

    do { // початок зовнішнього циклу з післяумовою для повторного виконання табулювання
        system("cls"); // очищення екрана консолі перед кожним новим виводом таблиці

        cout << "x\ty(x)" << endl; // виведення шапки таблиці із розділювачем-табуляцією (\t)

        double x = x0; // надання змінній x початкового значення x0 перед початком обчислень
        while (x <= xk + dx / 2.0) { // внутрішній цикл працює, поки x не перевищить xk (з урахуванням похибки)
            double y = 9.0 * (pow(x, 3) + pow(b, 3)) * tan(x); // обчислення значення функції y(x) за формулою

            cout << x << "\t" << y << endl; // виведення поточного значення аргументу x та результату y через табуляцію

            x += dx; // збільшення значення аргументу x на крок dx для наступного кроку
        }

        system("pause"); // системна затримка екрана до натискання будь-якої клавіші користувачем

        cout << "\nБажаєте продовжити? (1 - так, 0 - ні): "; // виведення прохання вказати вибір щодо повтору
        cin >> continueProgram; // зчитування введеного значення у змінну-прапорець continueProgram

    } while (continueProgram != 0); // умова повтору: цикл виконається знову, якщо введено число, відмінне від 0

    return 0; // повернення значення 0, що свідчить про успішне завершення програми
} // закриваюча дужка головної функції main