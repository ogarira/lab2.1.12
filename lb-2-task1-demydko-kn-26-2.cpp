#include <iostream> // Підключення бібліотеки для введення/виведення даних (cin, cout).
#include <cmath> // Підключення математичної бібліотеки (потрібна для функції fabs).
#include <Windows.h> // Підключення системних функцій Windows для роботи з консоллю.using namespace std; // Використання стандартного простору імен, щоб не писати "std::" перед cout та cin.
int main() { // Головна функція програми, з якої починається її виконання комп'ютером.
    using namespace std;
SetConsoleCP(65001);// Налаштування кодування UTF-8 для коректного зчитування українських літер з клавіатури.
SetConsoleOutputCP(65001);// Налаштування кодування UTF-8 для правильного виведення українського тексту в консоль.
int Pr; // Оголошення цілої змінної Pr для збереження вибору користувача в меню.
// Виведення на екран головного меню програми та опис доступних варіантів.
    cout << "Оберіть дію (параметр Pr):\n";
    cout << "1 - Обчислити n-й елемент ряду\n";
    cout << "2 - Обчислити суму перших n елементів ряду\n";
    cout << "3 - Обчислити суму ряду з точністю Eps = 10^-5\n";
    cout << "Ваш вибір (1, 2 або 3): ";
 cin >> Pr; // Очікування та зчитування введеного користувачем числа у змінну Pr.
switch (Pr) { // Початок блоку розгалуження switch, який виконує потрібний код залежно від значення Pr.
        case 1: { // Початок блоку для випадку, якщо користувач обрав пункт 1.
        int n; // Оголошення цілої змінної n для збереження порядкового номера елемента.
        cout << "Введіть номер елемента n (n >= 0): "; // Виведення підказки для введення.
        cin >> n; // Зчитування номера елемента n з клавіатури.

double un = 1.0 / (2.0 * n + 1.0);// Обчислення знаменника та базового значення елемента ряду за формулою (без врахування знака).
if (n % 2 != 0) {   // Перевірка: якщо номер n непарний, то елемент ряду має бути від'ємним.
un = -un; // Зміна знака елемента на мінус (ефективна заміна функції pow).
        } // Кінець перевірки умови if.
cout << "Елемент u_" << n << " = " << un << endl;// Виведення результату обчислення n-го елемента у консоль.
break; // Вихід із конструкції switch (завершення роботи пункту 1).
    } // Кінець блоку case 1.
        case 2: { // Початок блоку для випадку, якщо користувач обрав пункт 2.
        int n; // Оголошення цілої змінної n для збереження кількості елементів.
 cout << "Введіть кількість елементів n (n > 0): "; // Виведення підказки для користувача.
 cin >> n; // Зчитування кількості елементів n з клавіатури.
double sum = 0.0; // Створення дійсної змінної sum для накопичення суми, початкове значення 0.
double u = 1.0; // Створення дійсної змінної u для збереження поточного елемента ряду (перший елемент = 1).
for (int m = 0; m < n; m++) { // Цикл for, який виконається рівно n разів (лічильник m рахує від 0 до n-1).
sum += u; // Додавання значення поточного елемента u до загальної суми.
u *= -(2.0 * m + 1.0) / (2.0 * m + 3.0);// Обчислення наступного елемента через рекурентну формулу за допомогою скороченого оператора *=.
} // Кінець циклу for.
cout << "Сума перших " << n << " елементів ряду = " << sum << endl;// Виведення результату обчисленої суми n елементів у консоль.
break; // Вихід із конструкції switch (завершення роботи пункту 2).
    } // Кінець блоку case 2.
case 3: { // Початок блоку для випадку, якщо користувач обрав пункт 3.
double eps = 1e-5; // Оголошення дійсної змінної для точності обчислень (0.00001).
double sum = 0.0; // Створення дійсної змінної sum для накопичення суми ряду.
double u = 1.0; // Початкове значення першого члена ряду (дорівнює 1).
int m = 0; // Лічильник кількості доданих членів ряду (ітерацій).
while (fabs(u) >= eps) {// Цикл while працює доти, доки абсолютна величина (модуль) поточного елемента u більша або дорівнює точності eps.
sum += u; // Додавання поточного елемента u до загальної суми ряду.
u *= -(2.0 * m + 1.0) / (2.0 * m + 3.0);// Обчислення наступного члена ряду за рекурентним співвідношенням.
m++; // Збільшення лічильника членів ряду на 1 на кожному кроці циклу.
} // Кінець циклу while.
double control = atan(1.0); // Обчислення контрольного еталонного значення (арктангенс одиниці дорівнює Pi/4).
// Виведення фінальних результатів обчислень та порівняння з еталоном.
cout << "Обчислена сума ряду = " << sum << endl;
cout << "Кількість врахованих членів ряду = " << m << endl;
cout << "Контрольне значення (Pi / 4) = " << control << endl;
cout << "Абсолютна похибка = " << fabs(sum - control) << endl;// Обчислення та виведення абсолютної похибки (різниці між нашою сумою та знайденим контрольним значенням).
break; // Вихід із конструкції switch (завершення роботи пункту 3).
} // Кінець блоку case 3.
default: { // Блок, який виконується, якщо користувач ввів будь-яке інше число, крім 1, 2 або 3.
cout << "Некоректний вибір! Введіть значення 1, 2 або 3." << endl; // Виведення повідомлення про помилку.
break; // Вихід із блоку за замовчуванням.
} // Кінець блоку default.
} // Закриття фігурної дужки конструкції розгалуження switch.
system("pause"); // Зупинка виконання програми, щоб консольне вікно не закрилося відразу і можна було побачити результат.
return 0; // Сигнал для операційної системи про те, що програма завершила свою роботу успішно та без помилок.
} // Кінець головної функції main.